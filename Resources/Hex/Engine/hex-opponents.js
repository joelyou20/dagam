function hexDeckPower(cards) {
  const defs = cards.map((id) => hexDef(id)).filter(Boolean),
    n = defs.length;
  if (!n)
    return {
      score: 0,
      rank: "Novice",
      rankIndex: 0,
      base: 0,
      synergy: 0,
      consistency: 0,
    };
  const count = (num) => defs.filter((c) => hexNum(c) === num).length,
    units = defs.filter((c) => c.card_type === "Creature"),
    equipment = defs.filter((c) => c.subtype === "Equipment").length,
    back = [15, 18, 36].reduce((n, id) => n + count(id), 0),
    tanks = units.filter((c) => c.hp >= 5).length;
  let base =
    (defs.reduce(
      (s, c) =>
        s +
        (c.card_type === "Creature"
          ? c.attack * 2 + c.hp * 0.8 + (HEX_CARD_ABILITY_POWER[hexNum(c)] || 0)
          : HEX_SUPPORT_POWER[hexNum(c)] || 0),
      0,
    ) /
      n) *
    10;
  // Duplicated Mossgrubs, tutor targets, healing payoffs, protection and stun follow-up.
  const synergy =
    ((Math.min(6, Math.max(0, count(29) - 1)) * 2.5 +
      Math.min(count(5), equipment) * 0.65 +
      Math.min(count(59), count(10) + count(17) + count(31) + count(44)) * 0.8 +
      Math.min(back, tanks) * 0.35 +
      Math.min(count(26), Math.max(0, count(2) + count(26) - 1)) * 0.5 +
      Math.min(count(9), units.filter((c) => c.attack <= 1).length) * 0.25) *
      20) /
    n;
  const rate = units.length / n,
    consistency =
      ((Math.min(6, Math.max(0, units.length - 10)) * 0.5 -
        Math.max(0, 0.55 - rate) * 35 -
        Math.max(0, equipment - units.length / 2) * 0.7) *
        20) /
      n,
    score = Math.round((base + synergy + consistency) * 10) / 10;
  const rankIndex = [58, 62, 66, 70, 74, 78, 80, 86].filter((cut) => score >= cut).length;
  return {
    score,
    rank: HEX_DECK_RANKS[rankIndex],
    rankIndex,
    base: Math.round(base * 10) / 10,
    synergy: Math.round(synergy * 10) / 10,
    consistency: Math.round(consistency * 10) / 10,
    ...hexCalibratedDeckRating(cards),
  };
}
