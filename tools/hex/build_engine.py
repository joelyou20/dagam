"""Build the generated QuickJS bundle from readable rule modules and card data."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ENGINE = ROOT / "Resources/Hex/Engine"
DATA = ROOT / "Resources/Hex/Data"
MODULES = (
    "platform",
    "hex-formats",
    "hex-engine",
    "hex-planes",
    "hex-effects",
    "hex-resolve",
    "hex-arcana",
    "hex-elderberry",
    "hex-ai",
    "hex-ai-ascended",
    "hex-opponents",
    "hex-enemy-decks",
    "bridge",
)


def load_json(name):
    return json.loads((DATA / name).read_text())


def constant(name, value):
    return f"const {name} = {json.dumps(value, indent=2, ensure_ascii=False)};\n"


def build():
    cards = load_json("cards.json")
    illustration_rares = load_json("illustration-rares.json")
    full_art = [
        {**card, "id": card["id"] + "-FA", "baseId": card["id"], "finish": "full-art"}
        for card in cards
    ]
    rare_prints = [
        {
            **card,
            "id": card["id"] + "-IR",
            "baseId": card["id"],
            "finish": "illustration-rare",
        }
        for card in cards
        if card["id"] in illustration_rares
    ]
    sections = [
        "// Generated by tools/hex/build_engine.py. Edit the individual source modules.\n",
        constant("HEX_CARDS", cards),
        constant("HEX_PRINTS", cards + full_art + rare_prints),
        "const HEX_CARD = Object.fromEntries(HEX_PRINTS.map(card => [card.id, card]));\n",
        constant("HEX_KEYWORDS", load_json("keywords.json")),
        constant("HEX_RESOURCE_DECKS", load_json("power-enemy-decks.json")),
    ]
    for module in MODULES:
        sections.append(f"\n// {module}\n{(ENGINE / (module + '.js')).read_text()}\n")
    # The native bridge uses this final expression to confirm successful evaluation.
    sections.append('\n"ready";\n')
    (ENGINE / "battle.js").write_text("".join(sections))
    print(f"Battle bundle ready: {len(cards)} cards")


if __name__ == "__main__":
    build()
